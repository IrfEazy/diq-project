"""Build v3 report assets from Report/v3_assets.json.

Copies the listed figures from Plot/v3/<exp_id>/ to Report/Images/v3/<exp_id>/ and writes one LaTeX tabular per
experiment to Report/Tables/v3/<exp_id>.tex from Plot/v3/results/<exp_id>.json (via library.v3.runner).
Run from the repo root: uv run --frozen python Report/tools/build_v3_assets.py
"""
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from library.v3.runner import load_results, summarise  # noqa: E402

MANIFEST = ROOT / "Report" / "v3_assets.json"
PLOT_DIR = ROOT / "Plot" / "v3"
IMAGES_DIR = ROOT / "Report" / "Images" / "v3"
TABLES_DIR = ROOT / "Report" / "Tables" / "v3"
SCRIPT = "Report/tools/build_v3_assets.py"
LATEX_SPECIALS = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
                  "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def fail(msg):
    sys.exit(f"build_v3_assets: error: {msg}")


def tex(text):
    return "".join(LATEX_SPECIALS.get(ch, ch) for ch in str(text))


def fmt_x(x):
    return format(x, "g") if isinstance(x, float) else str(x)


def pick_x(payload, spec, exp_id):
    axis = payload["x_axis"]
    if "x" in spec:
        xs = list(spec["x"])
        for x in xs:
            if x not in axis:
                fail(f"{exp_id}: x value {x!r} not in x_axis {axis}")
        return xs
    return [axis[0], axis[len(axis) // 2], axis[-1]]


def table_rows(spec, exp_id):
    if "rows" in spec:
        return [(c, m) for c, m in spec["rows"]]
    return [(c, m) for c in spec["conditions"] for m in spec["models"]]


def build_table(exp_id, spec):
    payload = load_results(exp_id)
    metric = spec.get("metric", "test_nrmse")
    xs = pick_x(payload, spec, exp_id)
    rows = table_rows(spec, exp_id)
    for cond, model in rows:
        if cond not in payload["conditions"]:
            fail(f"{exp_id}: condition {cond!r} not in {payload['conditions']}")
        if model not in payload["models"]:
            fail(f"{exp_id}: model {model!r} not in {payload['models']}")
    summ = summarise(payload, metric)
    cell = {(r.condition, r.model, r.x): r for r in summ.itertuples()}
    lines = [
        f"% Generated by {SCRIPT} from Plot/v3/results/{exp_id}.json (metric {metric}); do not edit by hand.",
        "% Cells are mean $\\pm$ SD over seeds (folds averaged within seed); the band is descriptive, not a confidence interval.",
        "\\begin{tabular}{ll" + "r" * len(xs) + "}",
        "\\hline",
        "Condition & Model & " + " & ".join(tex(fmt_x(x)) for x in xs) + " \\\\",
        "\\hline",
    ]
    for cond, model in rows:
        cells = []
        for x in xs:
            r = cell.get((cond, model, x))
            if r is None:
                fail(f"{exp_id}: no summarised value for ({cond!r}, {model!r}, x={x!r})")
            cells.append(f"{r.mean:.3f} $\\pm$ {r.sd:.3f}")
        lines.append(f"{tex(cond)} & {tex(model)} & " + " & ".join(cells) + " \\\\")
    lines += ["\\hline", "\\end{tabular}", ""]
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    (TABLES_DIR / f"{exp_id}.tex").write_text("\n".join(lines), encoding="utf-8", newline="\n")


def copy_figures(exp_id, names):
    for name in names:
        src = PLOT_DIR / exp_id / name
        if not src.is_file():
            fail(f"{exp_id}: figure {name} not found at {src}")
        dst = IMAGES_DIR / exp_id / name
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
        print(f"figure {dst.relative_to(ROOT)}")


def main():
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    for exp_id, spec in manifest.items():
        copy_figures(exp_id, spec.get("figures", []))
        if "table" in spec:
            build_table(exp_id, spec["table"])
            print(f"table  Report/Tables/v3/{exp_id}.tex")


if __name__ == "__main__":
    main()
