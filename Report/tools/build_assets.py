"""Build the report assets from Report/assets.json.

Copies the listed figures from Plot/<exp_id>/ to Report/Images/<exp_id>/ and writes one LaTeX tabular per
experiment to Report/Tables/<exp_id>.tex from Plot/results/<exp_id>.json (via library.runner). The output
directory is the runner's (DIQ_OUT_DIR or Plot); a relative one is resolved from the repo root.
Run: uv run --frozen python Report/tools/build_assets.py (the working directory does not matter).
"""
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from library.runner import load_results, out_dir_default, results_path, summarise  # noqa: E402

MANIFEST = ROOT / "Report" / "assets.json"
PLOT_DIR = ROOT / out_dir_default()  # an absolute DIQ_OUT_DIR wins over ROOT
IMAGES_DIR = ROOT / "Report" / "Images"
TABLES_DIR = ROOT / "Report" / "Tables"
RESULTS_DIR = Path(results_path("x", str(PLOT_DIR))).parent
RESULTS_NOTE = "Plot/results"  # header comment text; stable regardless of DIQ_OUT_DIR
SCRIPT = "Report/tools/build_assets.py"
LATEX_SPECIALS = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
                  "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def fail(msg):
    sys.exit(f"build_assets: error: {msg}")


def tex(text):
    return "".join(LATEX_SPECIALS.get(ch, ch) for ch in str(text))


def fmt_x(x):
    return format(x, "g") if isinstance(x, float) else str(x)


def pick_x(payload, spec, exp_id):
    axis = payload["x_axis"]
    if "x" in spec:
        xs = list(spec["x"])
        for x in xs:
            if x not in axis:
                fail(f"{exp_id}: x value {x!r} not in x_axis {axis}")
        return xs
    return [axis[0], axis[len(axis) // 2], axis[-1]]


def table_rows(spec, exp_id):
    if "rows" in spec:
        return [(c, m) for c, m in spec["rows"]]
    return [(c, m) for c in spec["conditions"] for m in spec["models"]]


def build_table(exp_id, spec):
    payload = load_results(str(RESULTS_DIR / f"{exp_id}.json"))
    metric = spec.get("metric", "test_nrmse")
    xs = pick_x(payload, spec, exp_id)
    rows = table_rows(spec, exp_id)
    for cond, model in rows:
        if cond not in payload["conditions"]:
            fail(f"{exp_id}: condition {cond!r} not in {payload['conditions']}")
        if model not in payload["models"]:
            fail(f"{exp_id}: model {model!r} not in {payload['models']}")
    summ = summarise(payload, metric)
    cell = {(r.condition, r.model, r.x): r for r in summ.itertuples()}
    lines = [
        f"% Generated by {SCRIPT} from {RESULTS_NOTE}/{exp_id}.json (metric {metric}); do not edit by hand.",
        "% Cells are mean $\\pm$ SD over seeds (folds averaged within seed); the band is descriptive, not a confidence interval.",
        "\\begin{tabular}{ll" + "r" * len(xs) + "}",
        "\\hline",
        "Condition & Model & " + " & ".join(tex(fmt_x(x)) for x in xs) + " \\\\",
        "\\hline",
    ]
    for cond, model in rows:
        cells = []
        for x in xs:
            r = cell.get((cond, model, x))
            if r is None:
                fail(f"{exp_id}: no summarised value for ({cond!r}, {model!r}, x={x!r})")
            cells.append(f"{r.mean:.3f} $\\pm$ {r.sd:.3f}")
        lines.append(f"{tex(cond)} & {tex(model)} & " + " & ".join(cells) + " \\\\")
    lines += ["\\hline", "\\end{tabular}", ""]
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    (TABLES_DIR / f"{exp_id}.tex").write_text("\n".join(lines), encoding="utf-8", newline="\n")


def copy_figures(exp_id, names):
    for name in names:
        src = PLOT_DIR / exp_id / name
        if not src.is_file():
            fail(f"{exp_id}: figure {name} not found at {src}")
        dst = IMAGES_DIR / exp_id / name
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
        print(f"figure {dst.relative_to(ROOT)}")


def check_manifest(manifest):
    if not isinstance(manifest, dict):
        fail(f"{MANIFEST}: expected a JSON object mapping exp_id to a spec")
    for exp_id, spec in manifest.items():
        if not isinstance(spec, dict):
            fail(f"{MANIFEST}: {exp_id}: spec must be an object")
        figures = spec.get("figures", [])
        if not isinstance(figures, list) or not all(isinstance(f, str) for f in figures):
            fail(f"{MANIFEST}: {exp_id}: 'figures' must be a list of file names")
        if not (RESULTS_DIR / f"{exp_id}.json").is_file():
            fail(f"{exp_id}: results file {RESULTS_DIR / f'{exp_id}.json'} not found (run the notebooks first)")
        for name in figures:
            if not (PLOT_DIR / exp_id / name).is_file():
                fail(f"{exp_id}: figure {name} not found at {PLOT_DIR / exp_id / name}")
        table = spec.get("table")
        if table is not None:
            if not isinstance(table, dict):
                fail(f"{MANIFEST}: {exp_id}: 'table' must be an object")
            if "rows" not in table and not ("conditions" in table and "models" in table):
                fail(f"{MANIFEST}: {exp_id}: 'table' needs 'rows' or both 'conditions' and 'models'")


def main():
    if not MANIFEST.is_file():
        fail(f"manifest {MANIFEST} not found")
    try:
        manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    except ValueError as exc:
        fail(f"{MANIFEST}: invalid JSON ({exc})")
    check_manifest(manifest)
    for exp_id, spec in manifest.items():
        copy_figures(exp_id, spec.get("figures", []))
        if "table" in spec:
            build_table(exp_id, spec["table"])
            print(f"table  {(TABLES_DIR / f'{exp_id}.tex').relative_to(ROOT)}")


if __name__ == "__main__":
    main()
